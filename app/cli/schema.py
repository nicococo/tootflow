"""tootflow schema — machine-readable tool manifest for agent harnesses.

Generated by introspecting the argparse tree, so it can never drift from the
real command surface. Output is a JSON tool dict: one entry per command with
name, description, invocation, and typed parameters.
"""
import argparse
import json
from importlib.metadata import version as _pkg_version

from app.cli.common import out_json


def _action_type(action: argparse.Action) -> str:
    if action.type is int:
        return "integer"
    if action.type is float:
        return "number"
    if isinstance(action, argparse._StoreTrueAction) or isinstance(action, argparse._StoreFalseAction):
        return "boolean"
    return "string"


def _describe_action(action: argparse.Action, parser: argparse.ArgumentParser) -> dict | None:
    """One parameter description from an argparse action (None for internal actions)."""
    if isinstance(action, (argparse._HelpAction, argparse._SubParsersAction, argparse._VersionAction)):
        return None
    if not action.option_strings:
        # positional
        param = {
            "name": action.dest,
            "type": _action_type(action),
            "required": bool(action.required),
        }
    else:
        is_flag = isinstance(action, (argparse._StoreTrueAction, argparse._StoreFalseAction))
        param = {
            "name": action.option_strings[-1],
            "aliases": action.option_strings[:-1],
            "type": "boolean" if is_flag else _action_type(action),
            "required": bool(action.required),
        }
        if is_flag:
            param["flag"] = True

    if action.choices:
        param["choices"] = list(action.choices)
    if action.help:
        param["description"] = action.help
    if action.default is not None and action.default is not argparse.SUPPRESS:
        param["default"] = action.default
    if not param.get("aliases"):
        param.pop("aliases", None)
    return param


def _describe_parser(prefix: list[str], parser: argparse.ArgumentParser,
                     parent_help: str | None = None) -> list[dict]:
    """Recursively describe a (sub)parser's commands."""
    commands = []
    subparsers = None
    own_actions = []
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            subparsers = action
        else:
            own_actions.append(action)

    if subparsers is None:
        params = [
            p for p in (_describe_action(a, parser) for a in own_actions) if p is not None
        ]
        commands.append({
            "name": "_".join(prefix),
            "invocation": ["tootflow"] + prefix,
            "description": parser.description or parent_help or "",
            "parameters": params,
        })
        return commands

    # container (group) level: describe each subcommand, carrying shared flags down
    shared = [
        p for p in (_describe_action(a, parser) for a in own_actions) if p is not None
    ]
    help_by_name = {ca.dest: ca.help for ca in getattr(subparsers, "_choices_actions", [])}
    for name, sub in subparsers.choices.items():
        child_help = help_by_name.get(name)
        for cmd in _describe_parser(prefix + [name], sub, child_help):
            cmd["parameters"] = shared + cmd["parameters"]
            commands.append(cmd)
    return commands


def build_schema() -> dict:
    from app.cli.main import build_parser  # local import — avoids a module cycle

    parser = build_parser()
    try:
        app_version = _pkg_version("tootflow")
    except Exception:
        app_version = "unknown"

    commands = _describe_parser([], parser)
    return {
        "tool": "tootflow",
        "version": app_version,
        "description": parser.description,
        "run_via": ["uv", "run", "tootflow"],  # prefix each invocation with this
        "conventions": {
            "output": "add --json to any command for machine-readable output",
            "exit_codes": {"0": "ok", "1": "error (message on stderr)", "2": "usage error"},
            "destructive": "commands that delete require --yes",
            "stdin": "pass '-' to --content/--file/--json-file to read from stdin",
            "content_limit": "500 characters per post (truncated silently)",
            "timezone": "all timestamps are UTC, ISO 8601",
            "account_scoping": "single-user; scope with --account @user@instance where offered",
        },
        "commands": commands,
    }


def cmd_schema(args: argparse.Namespace) -> int:
    out_json(build_schema())
    return 0
